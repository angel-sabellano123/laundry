    private void jButton1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jButton1MouseClicked
                                       
    String fullName = fullname.getText().trim();
    String userName = username.getText().trim();
    String contactNo = contact.getText().trim();
    String pass = new String(password.getPassword());
    String confirmPass = new String(jPasswordField2.getPassword());
    
    String hashedPassword = config.hashPassword(pass);
    
    String userRole = role.getText().trim();
    
    if (fullName.isEmpty() || userName.isEmpty() || contactNo.isEmpty() 
    || pass.isEmpty() || confirmPass.isEmpty() || userRole.isEmpty()) {

    JOptionPane.showMessageDialog(this, "All fields are required!");
    return;
}

    if (!pass.equals(confirmPass)) {
        JOptionPane.showMessageDialog(this, "Passwords do not match!");
        return;
    }

    try {
        config cfg = new config();

        String sql = "INSERT INTO users (full_name, username, contact, password, role) VALUES (?, ?, ?, ?, ?)";

        boolean inserted = cfg.insertRecord(sql,
                fullName,
                userName,
                contactNo,
                hashedPassword,
                userRole   // default role
        );

        if (inserted) {
            JOptionPane.showMessageDialog(this, "User added successfully!");

            admin.admindashboard ad = new admin.admindashboard();
            ad.setVisible(true);
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Failed to add user.");
        }

    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
    }

    }//GEN-LAST:event_jButton1MouseClicked

